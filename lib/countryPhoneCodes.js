// Unicode regional-indicator flags: each ASCII letter A-Z maps to a
// regional-indicator symbol at U+1F1E6 + (letter - 'A'), and a country's
// flag emoji is just its two-letter ISO code's symbols placed side by side.
// Renders natively on every OS Chrome/Safari/Firefox actually ship on --
// nothing to store, nothing that can go stale relative to the code itself.
function regionalIndicator(iso2) {
  return iso2
    .toUpperCase()
    .replace(/./g, (letter) => String.fromCodePoint(0x1f1e6 + letter.charCodeAt(0) - 65));
}

function flagEmoji(iso2) {
  return regionalIndicator(iso2);
}

const BY_ISO2 = new Map(COUNTRIES.map((c) => [c.iso2, c]));

function findByIso2(iso2) {
  return BY_ISO2.get((iso2 || '').toUpperCase()) || null;
}

// Flag precomputed once here, not in the template -- EJS has no reliable way
// to require() a module relative to the .ejs file's own path (it resolves
// against the process's cwd instead), so views/partials/phone-input.ejs
// takes this array as a plain local rather than requiring this module
// itself. Every route that renders a page including that partial imports
// this file normally (a real .js require, not from inside a template) and
// passes COUNTRIES_WITH_FLAGS straight through.
const COUNTRIES_WITH_FLAGS = COUNTRIES.map((c) => ({ ...c, flag: flagEmoji(c.iso2) }));

module.exports = { COUNTRIES, COUNTRIES_WITH_FLAGS, flagEmoji, findByIso2 };
